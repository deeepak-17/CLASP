#!/usr/bin/env python3
"""Collect the D1 corpus.

Acquires each configured source, filters it, and writes
``datasets/processed/corpus.jsonl`` plus a provenance manifest.

Usage::

    python scripts/collect_dataset.py                      # git clone (needs network)
    python scripts/collect_dataset.py --mode synthetic     # offline fixture corpus
    python scripts/collect_dataset.py --mode local         # use existing checkouts
    python scripts/collect_dataset.py --dry-run            # filter only, write nothing
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import replace
from pathlib import Path

import _bootstrap  # noqa: F401

from _cli import EXIT_OK, base_parser, emit, report_line, run_cli, setup_logging
from corpus.collector import CorpusCollector, load_corpus_config
from utils.logging_utils import get_logger
from utils.paths import project_paths
from utils.reporting import MarkdownReport

_LOG = get_logger(__name__)


def build_parser() -> argparse.ArgumentParser:
    parser = base_parser(__doc__.splitlines()[0])
    parser.add_argument(
        "--config", type=Path, default=None, help="Dataset config. Defaults to configs/dataset.yaml."
    )
    parser.add_argument(
        "--mode",
        choices=["git", "local", "synthetic"],
        default=None,
        help="Override corpus.acquisition.mode.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Discover and filter without writing the corpus or manifest.",
    )
    return parser


def _render_report(result, config) -> MarkdownReport:
    manifest = result.manifest
    report = MarkdownReport(
        title="CLASP-P5 · D1 Corpus Collection Report",
        subtitle="dataset sourcing and collection",
    )

    report.heading("1. Run summary")
    report.key_values(
        {
            "Corpus": f"{manifest.corpus_name} v{manifest.corpus_version}",
            "Acquisition mode": manifest.acquisition_mode,
            "Synthetic": manifest.synthetic,
            "Clusters (projects)": manifest.num_clusters,
            "Files collected": manifest.total_files,
            "Total lines": manifest.total_lines,
            "Total code lines": manifest.total_code_lines,
            "Total bytes": manifest.total_bytes,
            "Duplicates dropped": manifest.duplicates_dropped,
            "Corpus SHA-256": f"`{manifest.corpus_sha256[:16]}…`",
            "Elapsed": f"{result.elapsed_seconds:.3f}s",
        }
    )
    if manifest.synthetic:
        report.paragraph(
            "**This corpus is synthetic.** It exists to exercise the pipeline offline and "
            "must not be used for training or for any reported result."
        )

    report.heading("2. Per-source breakdown")
    report.table(
        ["Cluster", "Project", "Licence", "Ref", "Discovered", "Kept", "Code lines", "Bytes"],
        [
            [
                source.cluster_id,
                source.project_label,
                source.license,
                (source.resolved_ref or "—")[:12],
                source.files_discovered,
                source.files_kept,
                source.num_code_lines,
                source.num_bytes,
            ]
            for source in manifest.sources
        ],
    )

    report.heading("3. Filter outcomes")
    report.paragraph(
        "Every rejection is counted by reason, so a sudden change in corpus size can be "
        "attributed to a specific rule rather than guessed at."
    )
    skipped = manifest.filter_summary.get("skipped_by_reason", {})
    report.table(
        ["Reason", "Files"], [[reason, count] for reason, count in sorted(skipped.items())]
    )
    report.key_values(
        {
            "Include globs": ", ".join(f"`{g}`" for g in config.filters.include_globs),
            "Exclude rules": len(config.filters.exclude_globs),
            "Min code lines": config.filters.min_code_lines,
            "Max file bytes": config.filters.max_file_bytes,
            "Dedup by content": config.filters.drop_duplicate_content,
        }
    )

    report.heading("4. Licence verification")
    report.table(
        ["Cluster", "Licence", "Source"],
        [[s.cluster_id, s.license, s.source_url or "—"] for s in manifest.sources],
    )
    report.paragraph(
        "All licences must be permissive (BSD-3-Clause / Apache-2.0) for CLASP's on-premise "
        "enterprise framing to hold. See `docs/dataset_sourcing.md`."
    )

    report.rule()
    report.paragraph("Generated by `scripts/collect_dataset.py`.")
    return report


def main(args: argparse.Namespace) -> int:
    config = load_corpus_config(args.config)
    if args.mode:
        config = replace(config, acquisition=replace(config.acquisition, mode=args.mode))
        _LOG.info("Acquisition mode overridden to '%s'", args.mode)

    collector = CorpusCollector(config)
    result = collector.collect(dry_run=args.dry_run)
    manifest = result.manifest
    paths = project_paths()

    lines = [
        "",
        "CLASP-P5 · Corpus Collection",
        "=" * 60,
        f"  mode:      {manifest.acquisition_mode}{'  (SYNTHETIC)' if manifest.synthetic else ''}",
        f"  clusters:  {manifest.num_clusters}",
        f"  files:     {manifest.total_files}",
        f"  code lines:{manifest.total_code_lines:>8}",
        f"  duplicates dropped: {manifest.duplicates_dropped}",
        f"  elapsed:   {result.elapsed_seconds:.3f}s",
        "",
    ]
    for source in manifest.sources:
        lines.append(
            f"    {source.cluster_id:<12} {source.files_kept:>4} kept / "
            f"{source.files_discovered:>4} found   {source.num_code_lines:>7} code lines"
        )
    lines.append("")

    if args.dry_run:
        lines.append("  DRY RUN — nothing written.")
        lines.append("")
    else:
        lines.append(f"  corpus:   {paths.relative(result.corpus_path)}")
        lines.append(f"  manifest: {paths.relative(result.manifest_path)}")
        if not args.no_report:
            path = _render_report(result, config).write(paths.reports / "corpus_collection_report.md")
            lines.append(report_line(path))
        lines.append("")

    emit(lines)
    return EXIT_OK


if __name__ == "__main__":
    parsed = build_parser().parse_args()
    setup_logging(parsed)
    sys.exit(run_cli(main, parsed))
